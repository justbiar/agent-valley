// Inlines the language layer (app/public/i18n-tr.js + app/public/i18n.js) into the static city pages, which are
// served on their own without the console. Run after editing either file: node app/scripts/city-i18n.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const pub = path.join(root, "app", "public");
const block = "<!-- i18n:start (generated by app/scripts/city-i18n.mjs) -->\n<script>\n" +
  fs.readFileSync(path.join(pub, "i18n-tr.js"), "utf8").trim() + "\n</script>\n<script>\n" +
  fs.readFileSync(path.join(pub, "i18n.js"), "utf8").trim() + "\n</script>\n<!-- i18n:end -->";

for (const name of ["index.html", "agent-valley.html"]) {
  const file = path.join(root, name);
  let s = fs.readFileSync(file, "utf8");
  const re = /<!-- i18n:start[\s\S]*?<!-- i18n:end -->/;
  s = re.test(s) ? s.replace(re, () => block) : s.replace(/(<title>[^<]*<\/title>)/, (t) => t + "\n" + block);
  fs.writeFileSync(file, s);
  console.log("inlined language layer into", name);
}
